#!/usr/bin/env node

import { mkdir, readFile, readdir, rename, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const DEFAULT_API_URL = "https://api.trytilde.ai/api/v1/mcp/available-tool-groups";
const API_URL = process.env.TILDE_TOOL_PROVIDER_CATALOG_URL || DEFAULT_API_URL;
const ROOT = process.cwd();
const PROVIDER_DIRECTORY = path.join(ROOT, "tool-providers");
const GENERATED_CATALOG_PATH = path.join(ROOT, "snippets", "generated-tool-providers.jsx");
const GENERATED_MARKER = "{/* GENERATED: scripts/generate-tool-provider-pages.mjs */}";
const CHECK_ONLY = process.argv.includes("--check");

const yaml = (value) => JSON.stringify(String(value));
const providerRoute = (slug) => String(slug || "")
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, "-")
  .replace(/^-+|-+$/g, "");
const titleCase = (value) => String(value || "Tools")
  .replaceAll("_", " ")
  .replace(/\b\w/g, (letter) => letter.toUpperCase());
const mdxText = (value) => String(value || "")
  .replace(/\s+/g, " ")
  .trim()
  .replaceAll("{", "&#123;")
  .replaceAll("}", "&#125;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")
  .replaceAll("[", "\\[")
  .replaceAll("]", "\\]");

const credentialsFor = (source) => [
  ...new Set((source.credential_sources || [])
    .map((credential) => credential.display_name || credential.name)
    .filter(Boolean)),
];

const providerFromApi = (source, includePopularTools = false) => ({
  name: source.name,
  slug: source.type_id,
  initials: source.name.replace(/[^a-zA-Z0-9]/g, "").slice(0, 2).toUpperCase(),
  category: titleCase(source.categories?.[0]),
  summary: source.documentation || `${source.name} tools for AI agents.`,
  auth: credentialsFor(source),
  iconSources: [source.metadata?.icon_url].filter(Boolean),
  toolCount: (source.tools || []).length,
  tools: includePopularTools
    ? (source.tools || []).slice(0, 12).map((tool) => [tool.name, tool.documentation || ""])
    : [],
});

const fetchCatalog = async () => {
  const items = [];
  let nextPageToken;

  do {
    const url = new URL(API_URL);
    url.searchParams.set("page_size", "100");
    url.searchParams.set("deployment_alias", "latest");
    if (nextPageToken) url.searchParams.set("next_page_token", nextPageToken);

    const response = await fetch(url, {
      headers: { Accept: "application/json" },
      signal: AbortSignal.timeout(30_000),
    });
    if (!response.ok) {
      throw new Error(`Tool provider API returned ${response.status} ${response.statusText}`);
    }

    const page = await response.json();
    if (!Array.isArray(page.items)) throw new Error("Tool provider API response is missing items");
    items.push(...page.items);
    nextPageToken = page.next_page_token;
  } while (nextPageToken);

  const invalid = items.find((provider) => !provider?.type_id || !provider?.name);
  if (invalid) throw new Error("Tool provider API returned a provider without type_id or name");

  return items.sort((a, b) => a.name.localeCompare(b.name));
};

const renderCatalog = (sources) => {
  const providers = sources.map((source) => providerFromApi(source));
  return `// Generated by scripts/generate-tool-provider-pages.mjs from ${DEFAULT_API_URL}.\n// Do not edit this file directly.\n\nexport const providers = ${JSON.stringify(providers, null, 2)};\n`;
};

const renderProviderPage = (source) => {
  const provider = providerFromApi(source, true);
  const toolCount = provider.toolCount;
  const description = `Explore ${toolCount} ${source.name} tools for AI agents in Tilde, including supported authentication and MCP capabilities.`;
  const authSentence = provider.auth.length
    ? `Connect with ${mdxText(provider.auth.join(", "))}.`
    : "No authentication method is currently advertised.";
  const popularTools = provider.tools.length
    ? `## Popular ${mdxText(source.name)} tools\n\n${provider.tools
      .map(([name, documentation]) => `- **${mdxText(name)}** — ${mdxText(documentation)}`)
      .join("\n")}`
    : `## ${mdxText(source.name)} tools\n\nThis provider does not currently publish tools in the public catalog.`;

  return `---
title: ${yaml(`${source.name} tools for AI agents`)}
sidebarTitle: ${yaml(source.name)}
description: ${yaml(description)}
keywords:
  - ${yaml(`${source.name} AI tools`)}
  - ${yaml(`${source.name} MCP integration`)}
  - ${yaml(`${source.name} tools for AI agents`)}
  - "Tilde tool providers"
  - "MCP tools"
"og:title": ${yaml(`${source.name} tools for AI agents | Tilde`)}
"og:description": ${yaml(description)}
mode: "wide"
---

import {
  PUBLIC_CATALOG_URL,
  iconAliases,
  iconUrl,
  providerFromApi,
  ProviderLogo,
  ToolProviderDetail,
} from "/snippets/tool-provider-browser.jsx";

export const provider = ${JSON.stringify(provider, null, 2)};

${GENERATED_MARKER}

${mdxText(provider.summary)}

Tilde exposes **${toolCount} ${mdxText(source.name)} ${toolCount === 1 ? "tool" : "tools"}** for AI agents through MCP. ${authSentence}

<ToolProviderDetail provider={provider} ProviderLogo={ProviderLogo} />

${popularTools}

## Connect ${mdxText(source.name)} to an AI agent

Add ${mdxText(source.name)} from the [Tilde dashboard](https://api.trytilde.ai/tools/available-tool-providers), then enable the tools your agent needs on an MCP server. [Learn how tools work in Tilde](/tools).

[Browse every Tilde tool provider](/tool-providers/index) or [compare Tilde-managed and self-managed authentication](/tool-providers/managed-auth).
`;
};

const readIfPresent = async (filePath) => {
  try {
    return await readFile(filePath, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
};

const writeAtomic = async (filePath, content) => {
  const temporaryPath = `${filePath}.tmp`;
  await writeFile(temporaryPath, content, "utf8");
  await rename(temporaryPath, filePath);
};

const main = async () => {
  const sources = await fetchCatalog();
  if (sources.length === 0) throw new Error("Tool provider API returned an empty catalog");

  const expected = new Map();
  expected.set(GENERATED_CATALOG_PATH, renderCatalog(sources));
  for (const source of sources) {
    const slug = providerRoute(source.type_id);
    if (!slug) throw new Error(`Could not create a route for provider ${source.type_id}`);
    expected.set(path.join(PROVIDER_DIRECTORY, `${slug}.mdx`), renderProviderPage(source));
  }

  const currentFiles = await readdir(PROVIDER_DIRECTORY, { withFileTypes: true });
  const staleGeneratedFiles = [];
  for (const entry of currentFiles) {
    if (!entry.isFile() || !entry.name.endsWith(".mdx")) continue;
    const filePath = path.join(PROVIDER_DIRECTORY, entry.name);
    if (expected.has(filePath)) continue;
    const content = await readIfPresent(filePath);
    if (content?.includes(GENERATED_MARKER)) staleGeneratedFiles.push(filePath);
  }

  const changed = [];
  for (const [filePath, content] of expected) {
    if (await readIfPresent(filePath) !== content) changed.push(filePath);
  }

  if (CHECK_ONLY) {
    if (changed.length || staleGeneratedFiles.length) {
      for (const filePath of [...changed, ...staleGeneratedFiles]) {
        console.error(path.relative(ROOT, filePath));
      }
      throw new Error("Generated tool provider documentation is out of date");
    }
    console.log(`Tool provider documentation matches ${sources.length} API providers.`);
    return;
  }

  await mkdir(path.dirname(GENERATED_CATALOG_PATH), { recursive: true });
  await mkdir(PROVIDER_DIRECTORY, { recursive: true });
  for (const [filePath, content] of expected) await writeAtomic(filePath, content);
  for (const filePath of staleGeneratedFiles) await unlink(filePath);

  console.log(`Generated ${sources.length} provider routes and the catalog fallback from ${API_URL}.`);
};

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
